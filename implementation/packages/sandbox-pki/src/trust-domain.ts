import type { SandboxKeyStore } from "./keystore.js";
import {
  authorityKeyIdentifier,
  basicConstraints,
  certificatePolicies,
  issueCertificate,
  keyUsage,
  type NameAttribute,
  OID,
  randomSerial,
  type Signer,
  subjectKeyIdentifier,
} from "./x509.js";

/**
 * The sandbox's trust domain (ADR 0014 Decision 2): its CAs and signers, each a key in the key store
 * and a certificate.
 *
 * Three domains, kept apart as the ARF keeps them apart: access certificates, registration
 * certificates and PIDs. Each has a CA that goes on its list and an "untrusted" twin that never does,
 * used only for the unknown-issuer defects (AC-01, RC-04, PID-01). Defective certificates of every
 * other kind are issued by the trusted CA, so a wallet reaches the defect under test (ADR 0014
 * Decision 3).
 */

/** The sandbox's own policy OID (specification Q-S7, decided 12 November 2026). */
export const SANDBOX_POLICY_OID = "2.25.122722476230885567871422612338706645671";

export const SANDBOX_ORGANISATION = "EDTP Sandbox - TEST ONLY";
/** ETSI TS 119 602 §6.8: the list signer's C and O match the scheme territory and operator. */
export const SANDBOX_TERRITORY = "EU";

export type ListKind = "WRPAC" | "WRPRC" | "PID";

export interface DomainMember {
  /** The key's name in the store, and the certificate's file name. */
  readonly name: string;
  readonly commonName: string;
  /** Which list carries it, if any. The untrusted CAs and the signers are on none. */
  readonly listedOn?: ListKind;
  /** A root CA (self-signed, `keyCertSign` and `cRLSign`), or a leaf issued by `issuer`. */
  readonly kind: "root" | "leaf";
  readonly issuer?: string;
}

