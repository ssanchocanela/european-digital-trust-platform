export const nameOf = (commonName: string): NameAttribute[] => [
  { type: OID.countryName, value: SANDBOX_TERRITORY },
  { type: OID.organizationName, value: SANDBOX_ORGANISATION },
  { type: OID.commonName, value: commonName },
];

const DAY = 86_400_000;
/** Two years, ADR 0014 Decision 2. */
export const ROOT_VALIDITY_DAYS = 730;
export const SIGNING_LEAF_VALIDITY_DAYS = 365;

export interface IssuedMember {
  readonly member: DomainMember;
  readonly certificate: Buffer;
}

/**
 * Generate every key and certificate of the domain. Refuses to run if any key already exists: the
 * domain's anchors are what wallets pin, so they are created once and rotated deliberately, never
 * regenerated by accident.
 */
export async function createTrustDomain(
  store: SandboxKeyStore,
  now: Date,
): Promise<IssuedMember[]> {
  for (const member of TRUST_DOMAIN) {
    if (await store.has(member.name)) {
      throw new Error(
        `the trust domain already exists (found key ${member.name}); refusing to regenerate it`,
      );
    }
  }
  const signers = new Map<string, Signer>();
  const certificates = new Map<string, Buffer>();
  const issued: IssuedMember[] = [];
  for (const member of TRUST_DOMAIN) {
    const signer = await store.create(member.name);
    signers.set(member.name, signer);
    const subject = nameOf(member.commonName);
    let certificate: Buffer;
    if (member.kind === "root") {
      const isCa = member.name !== "lote-signer";
      certificate = issueCertificate(
        {
          serial: randomSerial(),
          issuer: subject,
          subject,
          notBefore: now,
          notAfter: new Date(now.getTime() + ROOT_VALIDITY_DAYS * DAY),
          subjectPublicKey: signer.publicKey,
          extensions: [
            basicConstraints(isCa, isCa ? 0 : undefined),
            keyUsage(isCa ? ["keyCertSign", "cRLSign"] : ["digitalSignature"]),
            subjectKeyIdentifier(signer.publicKey),
            certificatePolicies([{ policy: SANDBOX_POLICY_OID }]),
          ],
        },
        signer,
      );
    } else {
      const issuerMember = TRUST_DOMAIN.find((m) => m.name === member.issuer);
      const issuerSigner = member.issuer ? signers.get(member.issuer) : undefined;
      if (!issuerMember || !issuerSigner)
        throw new Error(`issuer of ${member.name} not created first`);
      certificate = issueCertificate(
        {
          serial: randomSerial(),
          issuer: nameOf(issuerMember.commonName),
          subject,
          notBefore: now,
          notAfter: new Date(now.getTime() + SIGNING_LEAF_VALIDITY_DAYS * DAY),
          subjectPublicKey: signer.publicKey,
          extensions: [
            basicConstraints(false),
            keyUsage(["digitalSignature"]),
            subjectKeyIdentifier(signer.publicKey),
            authorityKeyIdentifier(issuerSigner.publicKey),
            certificatePolicies([{ policy: SANDBOX_POLICY_OID }]),
          ],
        },
        issuerSigner,
      );
    }
    certificates.set(member.name, certificate);
    issued.push({ member, certificate });
  }
  return issued;
}
